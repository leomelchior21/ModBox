/**
 * Twelve hand-drawn streets of the fiesta. Each map is a grid of 2 m cells, read top to bottom:
 *
 *   #  %  |  =   tall walls (the town picks how each kind looks)      O  a bullseye target on a wall
 *   o  f         low barrels/planters and fountains (cover, 1 m high)    G  a gate that opens once every bullseye is hit
 *   .            street                                                ,  plaza to paint red
 *   P            you start here                                        X  the fiesta exit
 *   A  H         tomato crate, churros (dry you off)                   c  m  b  cherry, mega and bouncy tomatoes
 *   g            a golden tomato
 *   M  S  U  V  K   Limpiabots: mop, hose, umbrella, vacuum and La Gran Lavadora
 */
export type TomatoGoal = 'robots' | 'zone' | 'targets' | 'golden' | 'exit' | 'boss';
export interface TomatinaLevel {
  name: string; tip: string; map: readonly string[];
  /** Direction you face at the start: 0 east, 1 south, 2 west, 3 north. */
  face: number;
  goals: readonly [TomatoGoal, number][];
  /** How quick and sharp-eyed the robots are on this street (multiplies the difficulty mod). */
  pace: number;
  night?: boolean;
}

