/** After the twelfth street the fiesta loops with sharper robots. */
export function levelOf(level: number): TomatinaLevel {
  const n = Math.max(1, level), base = LEVELS[(n - 1) % LEVELS.length], loop = Math.floor((n - 1) / LEVELS.length);
  return loop ? { ...base, pace: base.pace + loop * .15 } : base;
}
export const levelName = (level: number) => levelOf(level).name + (level > LEVELS.length ? ` ${Math.ceil(level / LEVELS.length)}` : '');
